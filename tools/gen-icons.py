"""Converts the Lucide SVGs in /assets into XAML path geometry for the LucideIcon control.

    python tools/gen-icons.py

Lucide icons are 24x24, stroke-only (fill="none"). Every element is flattened into one
path string; numbers are re-emitted with explicit separators and command letters so the
XAML path-markup parser (stricter than SVG's) accepts them.
"""
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets"
OUT = ROOT / "src" / "WinBrowser" / "Controls" / "LucideIcons.g.cs"

ARG_COUNT = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def fmt(v: float) -> str:
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def parse_path(d: str) -> str:
    out, i, cmd = [], 0, None

    def skip():
        nonlocal i
        while i < len(d) and d[i] in " ,\t\r\n":
            i += 1

    def number():
        nonlocal i
        skip()
        m = NUMBER.match(d, i)
        if not m:
            raise ValueError(f"number expected at {i} in {d!r}")
        i = m.end()
        return float(m.group())

    def flag():
        nonlocal i
        skip()
        ch = d[i]
        if ch not in "01":
            raise ValueError(f"arc flag expected at {i} in {d!r}")
        i += 1
        return ch

    while True:
        skip()
        if i >= len(d):
            break
        relative_first_move = False
        if d[i].isalpha():
            cmd = d[i]
            i += 1
            # A path's first moveto is absolute even when lowercase; paths get joined, so say so.
            if not out and cmd == "m":
                cmd, relative_first_move = "M", True
        elif cmd is None:
            raise ValueError(d)
        lower = cmd.lower()
        if lower == "z":
            out.append(cmd)
            cmd = None
            continue
        if lower == "a":
            rx, ry, rot = number(), number(), number()
            large, sweep = flag(), flag()
            x, y = number(), number()
            out.append(f"{cmd} {fmt(rx)} {fmt(ry)} {fmt(rot)} {large} {sweep} {fmt(x)} {fmt(y)}")
        else:
            args = [number() for _ in range(ARG_COUNT[lower])]
            out.append(cmd + " " + " ".join(fmt(a) for a in args))
        # Implicit repeats after a moveto are linetos.
        if lower == "m":
            cmd = "l" if cmd == "m" or relative_first_move else "L"
    return " ".join(out)


def circle(el) -> str:
    cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
    return (f"M {fmt(cx - r)} {fmt(cy)} A {fmt(r)} {fmt(r)} 0 1 0 {fmt(cx + r)} {fmt(cy)} "
            f"A {fmt(r)} {fmt(r)} 0 1 0 {fmt(cx - r)} {fmt(cy)} Z")


def rect(el) -> str:
    x, y = float(el.get("x", 0)), float(el.get("y", 0))
    w, h = float(el.get("width")), float(el.get("height"))
    rx = float(el.get("rx", el.get("ry", 0)))
    if rx <= 0:
        return f"M {fmt(x)} {fmt(y)} H {fmt(x + w)} V {fmt(y + h)} H {fmt(x)} Z"
    r = fmt(rx)
    return (f"M {fmt(x + rx)} {fmt(y)} H {fmt(x + w - rx)} A {r} {r} 0 0 1 {fmt(x + w)} {fmt(y + rx)} "
            f"V {fmt(y + h - rx)} A {r} {r} 0 0 1 {fmt(x + w - rx)} {fmt(y + h)} "
            f"H {fmt(x + rx)} A {r} {r} 0 0 1 {fmt(x)} {fmt(y + h - rx)} "
            f"V {fmt(y + rx)} A {r} {r} 0 0 1 {fmt(x + rx)} {fmt(y)} Z")


def convert(svg: pathlib.Path) -> str:
    parts = []
    for el in ET.parse(svg).getroot().iter():
        tag = el.tag.split("}")[-1]
        if tag == "path":
            parts.append(parse_path(el.get("d")))
        elif tag == "circle":
            parts.append(circle(el))
        elif tag == "rect":
            parts.append(rect(el))
        elif tag == "line":
            parts.append(f"M {el.get('x1')} {el.get('y1')} L {el.get('x2')} {el.get('y2')}")
        elif tag in ("polyline", "polygon"):
            pts = NUMBER.findall(el.get("points"))
            pairs = [f"{pts[k]} {pts[k + 1]}" for k in range(0, len(pts), 2)]
            parts.append("M " + " L ".join(pairs) + (" Z" if tag == "polygon" else ""))
    return " ".join(parts)


def main():
    icons = {svg.stem: convert(svg) for svg in sorted(SRC.glob("*.svg"))}
    lines = [
        "// <auto-generated> by tools/gen-icons.py from /assets (Lucide, ISC license). Do not edit. </auto-generated>",
        "namespace WinBrowser.Controls;",
        "",
        "internal static class LucideIcons",
        "{",
        "    public static readonly IReadOnlyDictionary<string, string> Paths = new Dictionary<string, string>",
        "    {",
    ]
    lines += [f'        ["{name}"] = "{data}",' for name, data in icons.items()]
    lines += ["    };", "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
